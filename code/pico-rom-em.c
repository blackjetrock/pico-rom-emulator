void rom_emulate(void)
{

  irq_set_mask_enabled( 0xFFFFFFFF, false );

  while(1)
    {
      uint32_t gpio_states;
      BYTE db;
      unsigned int addr;
      unsigned int last_addr;
      
      //      gpio_put(DDIR_A15_PIN, 1);
      
      // read GPIOs
      gpio_states = sio_hw->gpio_in;
      
      // We look for CE
      if( gpio_states & (1 << CE_PIN) )
      	{
          // CE high, we are not selected
        }
      else
      	{

          
          // CE low, we are selected
          // ROM emulation so always a read of us
          // get address
          addr = (gpio_states >> 8) & ADDRESS_MASK;
	  
          // Get data and present it on bus
          set_data(rom_data[addr]);

          //          printf("\nA");
          //set_data(0xF8);
	  
#if TRACE_ON
          if( trace_running )
            {
              trace_addr[trace_i] = addr;
              trace_value[trace_i] = rom_data[addr];
              trace_type[trace_i++] = 'W';
              if( trace_i == TRACE_N )
                {
                  trace_running = 0;
                }
            }
#endif

          last_addr = addr;
          
          number_ce_assert++;
#if 1
          // Wait for CE to be de-asserted
          while(1)
            {
              gpio_states = sio_hw->gpio_in;
	      
              // We look for CE
              if( gpio_states & (1 << CE_PIN) )
                {
                  //                  printf("\nD");
                  // CE high, we are not selected
                  break;
                }

              // CE low, we are selected
              // ROM emulation so always a read of us
              // get address
              addr = (gpio_states >> 8) & ADDRESS_MASK;
              
              // Get data and present it on bus
              set_data(rom_data[addr]);
              
#if TRACE_ON
              if( trace_running && (last_addr != addr)  )
                {
                  trace_addr[trace_i] = addr;
                  trace_value[trace_i] = rom_data[addr];
                  trace_type[trace_i++] = 'W';
                  if( trace_i == TRACE_N )
                    {
                      trace_running = 0;
                    }
                }
#endif
              last_addr = addr;
            }
#endif
        }
    }
}

