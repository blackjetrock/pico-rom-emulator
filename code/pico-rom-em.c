#define MAX_ADDR_TRACE 1024*64
int trace_on = 0;
volatile int addr_trace_index = 0;
volatile uint16_t addr_trace[MAX_ADDR_TRACE];
volatile unsigned int number_ce_assert = 0;

void rom_emulate(void)
{

  irq_set_mask_enabled( 0xFFFFFFFF, false );

  while(1)
    {
      uint32_t gpio_states;
      BYTE db;
      unsigned int addr;
      unsigned int last_addr;

      // Get off bus
      gpio_put(DDIR_A15_PIN, 1);
      
      // read GPIOs
      gpio_states = sio_hw->gpio_in;
      
      // We look for CE and OE being low
      if( (gpio_states & CE_OE_MASK) != 0 )
      	{
          // CE high, we are not selected

        }
      else
      	{
          // CE and OE low, we are selected
          // Drive bus
          gpio_put(DDIR_A15_PIN, 0);
                
          // ROM emulation so always a read of us
          // get address
          addr = (gpio_states >> 8) & ADDRESS_MASK;
	  
          // Get data and present it on bus
          set_data(rom_data[addr]);

          //          printf("\nA");
          //set_data(0xF8);
	  
#if TRACE_ON
          if( trace_running )
            {
              trace_addr[trace_i] = addr;
              trace_value[trace_i] = rom_data[addr];
              trace_type[trace_i++] = 'R';
              if( trace_i == TRACE_N )
                {
                  trace_running = 0;
                }
            }
#endif

          last_addr = addr;
          
          number_ce_assert++;
#if 1
          // Wait for CE or OE to be de-asserted
          while(1)
            {
              gpio_states = sio_hw->gpio_in;
	      
              // We look for CE and OE to be non zero
              if( (gpio_states & CE_OE_MASK) != 0 )
                {
                  // get off bus quickly
                  gpio_put(DDIR_A15_PIN, 1);
                  
                  //                  printf("\nD");
                  // CE or OE high, we are not selected
#if TRACE_ON
                  if( trace_running && (last_addr != addr)  )
                    {
                      trace_addr[trace_i] = addr;
                      trace_value[trace_i] = rom_data[addr];
                      trace_type[trace_i++] = 'X';
                      if( trace_i == TRACE_N )
                        {
                          trace_running = 0;
                        }
                    }
#endif
                  break;
                }

              // CE and OE low, we are selected
              // ROM emulation so always a read of us
              // get address
              addr = (gpio_states >> 8) & ADDRESS_MASK;
              
              // Get data and present it on bus
              set_data(rom_data[addr]);
              
#if TRACE_ON
              if( trace_running && (last_addr != addr)  )
                {
                  trace_addr[trace_i] = addr;
                  trace_value[trace_i] = rom_data[addr];
                  trace_type[trace_i++] = 'L';
                  if( trace_i == TRACE_N )
                    {
                      trace_running = 0;
                    }
                }
#endif
              last_addr = addr;
            }
#endif
        }
    }
}

